-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT site.ID AS ENTITY_ID, site.NAME AS ENTITY_NAME,
       site.REGION, site.CATEGORY, site.RISK_TIER, site.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.PICKUP_COUNT) AS PICKUP_COUNT,
       SUM(observation.PAYOUT_PHP) AS PAYOUT_PHP,
       SUM(observation.ACCOUNTS_OPENED) AS ACCOUNTS_OPENED,
       SUM(observation.BLOCKER_COUNT) AS BLOCKER_COUNT,
       SUM(observation.DROPOUT_COUNT) AS DROPOUT_COUNT,
       SUM(observation.SLA_BREACHED) AS SLA_BREACH_COUNT,
       SUM(observation.FOLLOWUP_DUE) AS FOLLOWUP_DUE,
       SUM(observation.FOLLOWUP_COMPLETED) AS FOLLOWUP_COMPLETED,
       100.0 * (SUM(observation.PICKUP_COUNT) - SUM(observation.BLOCKER_COUNT)) / NULLIF(SUM(observation.PICKUP_COUNT), 0) AS BLOCKER_FREE_PCT,
       100.0 * SUM(observation.DROPOUT_COUNT) / NULLIF(SUM(observation.BLOCKER_COUNT), 0) AS BLOCKER_DROPOUT_PCT,
       100.0 * SUM(observation.FOLLOWUP_COMPLETED) / NULLIF(SUM(observation.FOLLOWUP_DUE), 0) AS FOLLOWUP_COMPLETION_PCT,
       AVG(observation.EKYC_ERROR_PCT) AS AVG_EKYC_ERROR_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.SITE_DAILY observation
JOIN RAW.SITES site ON site.ID = observation.ENTITY_ID
GROUP BY site.ID, site.NAME, site.REGION, site.CATEGORY, site.RISK_TIER, site.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(PICKUP_COUNT) AS PICKUP_COUNT, SUM(PAYOUT_PHP) AS PAYOUT_PHP, SUM(ACCOUNTS_OPENED) AS ACCOUNTS_OPENED,
       SUM(BLOCKER_COUNT) AS BLOCKER_COUNT, SUM(DROPOUT_COUNT) AS DROPOUT_COUNT,
       100.0 * SUM(DROPOUT_COUNT) / NULLIF(SUM(BLOCKER_COUNT), 0) AS BLOCKER_DROPOUT_PCT
FROM RAW.SITE_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.BLOCKER_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT BLOCKER_TYPE, SUM(BLOCKER_COUNT) AS BLOCKER_COUNT,
       SUM(DROPOUT_COUNT) AS DROPOUT_COUNT,
       SUM(SLA_BREACHED) AS SLA_BREACH_COUNT,
       SUM(PAYOUT_PHP) AS EXPOSED_PAYOUT_PHP,
       100.0 * SUM(DROPOUT_COUNT) / NULLIF(SUM(BLOCKER_COUNT), 0) AS BLOCKER_DROPOUT_PCT
FROM RAW.SITE_DAILY
WHERE BLOCKER_COUNT > 0
GROUP BY BLOCKER_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(PICKUP_COUNT) AS PICKUPS, SUM(ACCOUNTS_OPENED) AS OPENED, SUM(BLOCKER_COUNT) AS BLOCKERS,
         SUM(DROPOUT_COUNT) AS DROPOUTS, SUM(SLA_BREACHED) AS BREACHES, SUM(PAYOUT_PHP) AS PAYOUT_PHP,
         SUM(FOLLOWUP_DUE) AS FOLLOWUP_DUE, SUM(FOLLOWUP_COMPLETED) AS FOLLOWUP_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.SITE_DAILY
), book AS (SELECT COUNT(*) AS SITE_COUNT FROM RAW.SITES),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.PARTNER_DOCUMENTS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Blocker-Free Pickup Rate' AS TITLE,
         100.0 * (PICKUPS - BLOCKERS) / NULLIF(PICKUPS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Onboarding Blockers', BLOCKERS, '' FROM observations
  UNION ALL SELECT 3, 'Abandoned-Application Blockers', DROPOUTS, '' FROM observations
  UNION ALL SELECT 4, 'Blocker Dropout Rate', 100.0 * DROPOUTS / NULLIF(BLOCKERS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Same-Day SLA Breaches', BREACHES, '' FROM observations
  UNION ALL SELECT 6, 'Remittance Payouts (PHP M)', PAYOUT_PHP / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Remittance Pickups', PICKUPS, '' FROM observations
  UNION ALL SELECT 8, 'Dormant-Account Follow-Up Completion', 100.0 * FOLLOWUP_COMPLETED / NULLIF(FOLLOWUP_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Sites Monitored', SITE_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Partner Document Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Partner Documents Pending', PENDING, '' FROM documents
  UNION ALL SELECT 12, 'Savings Accounts Opened', OPENED, '' FROM observations
  UNION ALL SELECT 13, 'Pickup-to-Account Conversion', 100.0 * OPENED / NULLIF(PICKUPS, 0), '%' FROM observations
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER IN (1, 13) THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.BLOCKER_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
