-- Abandoned-application risk scoring and blocker-volume forecast over the synthetic snapshot.
-- Predicts P(abandoned-application blocker at the site in the next 7 days) per site and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.DROPOUT_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, a.CATEGORY, a.RISK_TIER, a.SITE_TENURE_YEARS,
       r.EKYC_ERROR_PCT, r.AVG_ONBOARD_MIN,
       AVG(r.EKYC_ERROR_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS EKYC_ERROR_7D,
       SUM(r.DROPOUT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS DROPOUT_30D,
       IFF(SUM(r.DROPOUT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'DROPOUT', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.SITE_DAILY r JOIN RAW.SITES a ON a.ID = r.ENTITY_ID
-- City-wide power interruptions are not site-driven, so they are excluded from training.
WHERE r.BLOCKER_TYPE <> 'Area power interruption';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.DROPOUT_TRAIN AS
SELECT CATEGORY, RISK_TIER, SITE_TENURE_YEARS, EKYC_ERROR_PCT, AVG_ONBOARD_MIN, EKYC_ERROR_7D, DROPOUT_30D, LABEL
FROM ML.DROPOUT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.DROPOUT_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, RISK_TIER, SITE_TENURE_YEARS, EKYC_ERROR_PCT, AVG_ONBOARD_MIN, EKYC_ERROR_7D, DROPOUT_30D, LABEL
FROM ML.DROPOUT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.DROPOUT_RISK_MODEL(
  INPUT_DATA => TABLE(ML.DROPOUT_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.DROPOUT_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.DROPOUT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'SITE_TENURE_YEARS', SITE_TENURE_YEARS,
           'EKYC_ERROR_PCT', EKYC_ERROR_PCT, 'AVG_ONBOARD_MIN', AVG_ONBOARD_MIN,
           'EKYC_ERROR_7D', EKYC_ERROR_7D, 'DROPOUT_30D', DROPOUT_30D)):probability:DROPOUT::FLOAT AS P
  FROM ML.DROPOUT_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'DROPOUT', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'DROPOUT', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'DROPOUT', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'DROPOUT', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per site (label unknown, so excluded from features).
CREATE TABLE ML.DROPOUT_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.DROPOUT_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.DROPOUT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'SITE_TENURE_YEARS', SITE_TENURE_YEARS,
           'EKYC_ERROR_PCT', EKYC_ERROR_PCT, 'AVG_ONBOARD_MIN', AVG_ONBOARD_MIN,
           'EKYC_ERROR_7D', EKYC_ERROR_7D, 'DROPOUT_30D', DROPOUT_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:DROPOUT::FLOAT, 4) AS DROPOUT_PROB_7D,
       CASE WHEN P:probability:DROPOUT::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:DROPOUT::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Programme-wide blocker-volume forecast (14 days) from the daily series, for onboarding-desk staffing.
CREATE VIEW ML.DAILY_BLOCKERS AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(BLOCKER_COUNT)::FLOAT AS BLOCKER_COUNT
FROM RAW.SITE_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.BLOCKER_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_BLOCKERS),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'BLOCKER_COUNT'
);

CREATE TABLE ML.BLOCKER_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS BLOCKER_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.BLOCKER_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
